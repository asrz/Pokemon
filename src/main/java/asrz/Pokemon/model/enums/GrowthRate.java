	public int getLevel(int xp) {
		int low = 0, high = 100;
		
		while (low < high - 1) {
			int mid = (low + high) / 2;
			int mid_xp = lookupTable[mid][ordinal()];
			if (mid_xp > xp) {
				high = mid - 1;
			} else {
				low = mid;
			}
		}
		
		if (lookupTable[high][ordinal()] <= xp) {
			return lookupTable[high][LEVEL_INDEX];
		}
		
		return lookupTable[low][LEVEL_INDEX];
	}
	
	public int getXpRequired(int level) {
		return lookupTable[level-1][ordinal()];
	}
	
	public static List<GrowthRate> list() {
		return Util.list(values());
	}

	public static GrowthRate fromPokeApiLabel(String label) {
		for (GrowthRate growthRate : values()) {
			if (growthRate.pokeApiLabel.equals(label)) {
				return growthRate;
			}
		}
		
		return null;
	}
